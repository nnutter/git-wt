package gitwt

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/spf13/cobra"
)

type zshCommandOptions struct {
	name  string
	out   string
	force bool
}

func NewZshCommand() *cobra.Command {
	options := new(zshCommandOptions)

	command := &cobra.Command{
		Use:   `zsh`,
		Short: `Generate zsh function and completion wrapping git-wt`,
		Args:  cobra.NoArgs,
		RunE:  options.Execute,
	}

	command.Flags().StringVarP(&options.name, `name`, `n`, `wt`, `name of generated zsh function`)
	command.Flags().StringVarP(&options.out, `out`, `o`, xdgDataHome()+`/zsh/site-functions`, `output directory for generated files`)
	command.Flags().BoolVarP(&options.force, `force`, `f`, false, `overwrite existing generated files`)

	return command
}

func (x *zshCommandOptions) Execute(command *cobra.Command, args []string) error {
	outDir := x.out

	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return fmt.Errorf(`create output directory: %w`, err)
	}

	functionPath := filepath.Join(outDir, x.name)
	completionPath := filepath.Join(outDir, `_`+x.name)

	if !x.force {
		if _, err := os.Stat(functionPath); err == nil {
			return fmt.Errorf(`function file %q already exists; use --force to overwrite`, functionPath)
		}
		if _, err := os.Stat(completionPath); err == nil {
			return fmt.Errorf(`completion file %q already exists; use --force to overwrite`, completionPath)
		}
	}

	if err := x.writeFunctionFile(functionPath); err != nil {
		return err
	}

	if err := x.writeCompletionFile(completionPath); err != nil {
		return err
	}

	fmt.Fprintf(command.ErrOrStderr(), "Wrote %s\n", functionPath)
	fmt.Fprintf(command.ErrOrStderr(), "Wrote %s\n", completionPath)
	fmt.Fprintf(command.ErrOrStderr(), "Ensure %s is on fpath. Restart zsh or run compinit if completion does not appear immediately.\n", outDir)

	return nil
}

func (x *zshCommandOptions) writeFunctionFile(target string) error {
	content := `# Generated by git-wt generate zsh
# DO NOT EDIT. Regenerate with git-wt generate zsh

` + x.name + `() {
    case "$1" in
    create)
        shift
        local no_cd=0 herdr=0 no_herdr=0 skip_next=0
        local -a forward=()
        local arg
        for arg in "$@"; do
            if (( skip_next )); then
                forward+=("$arg")
                skip_next=0
                continue
            fi
            case "$arg" in
            --no-cd)
                no_cd=1
                ;;
            -r|--herdr)
                herdr=1
                forward+=("$arg")
                ;;
            -R|--no-herdr)
                no_herdr=1
                forward+=("$arg")
                ;;
            -u|--upstream|--repo)
                forward+=("$arg")
                skip_next=1
                ;;
            --upstream=*|--repo=*|--current)
                forward+=("$arg")
                ;;
            -*)
                forward+=("$arg")
                ;;
            *)
                forward+=("$arg")
                ;;
            esac
        done
        # Write the created path to a temp file so git-wt keeps a real TTY for
        # interactive prompts (repo picker / name input). Capturing stdout would
        # blank the bubbletea UI.
        local path_file
        path_file=$(mktemp) || return $?
        GIT_WT_CREATE_PATH_FILE=$path_file command git-wt create "${forward[@]}"
        local create_status=$?
        local target_dir=""
        if [[ -s "$path_file" ]]; then
            target_dir=$(<"$path_file")
        fi
        rm -f "$path_file"
        if (( create_status != 0 )); then
            return $create_status
        fi
        if (( no_cd || herdr || ( ${HERDR_ENV:-0} == 1 && ! no_herdr ) )); then
            return 0
        fi
        if [[ -z "$target_dir" ]]; then
            echo "Created worktree path not reported" >&2
            return 1
        fi
        if ! [[ -d "$target_dir" ]]; then
            echo "Worktree not found at $target_dir" >&2
            return 1
        fi
        cd "$target_dir"
        ;;
    switch)
        shift
        local repo="" skip_next=0
        local arg name=""
        for arg in "$@"; do
            if (( skip_next )); then
                repo=$arg
                skip_next=0
                continue
            fi
            case "$arg" in
            --repo)
                skip_next=1
                ;;
            --repo=*)
                repo=${arg#--repo=}
                ;;
            -*)
                ;;
            *)
                name=$arg
                ;;
            esac
        done
        if [[ -z "$name" ]]; then
            echo "Usage: ` + x.name + ` switch [--repo <name>] <worktree>" >&2
            return 1
        fi

        local repo_name=""
        if [[ -n "$repo" ]]; then
            repo_name=$repo
        else
            local common
            common=$(git rev-parse --path-format=absolute --git-common-dir 2>/dev/null) || {
                echo "Not inside a registered repository worktree; pass --repo" >&2
                return 1
            }
            repo_name=${common:t}
            repo_name=${repo_name%.git}
        fi

        local worktree_root=${GIT_WT_WORKTREE_ROOT:-$HOME/worktrees}
        local target_dir="$worktree_root/$name/$repo_name"
        if [[ $(pwd) == "$target_dir" ]]; then
            echo "Already in $name"
            return 0
        fi
        if ! [[ -d "$target_dir" ]]; then
            echo "Worktree $name not found at $target_dir" >&2
            return 1
        fi
        cd "$target_dir"
        ;;
    remove|migrate)
        # Snapshot cwd, then leave it before the source path may disappear.
        # remove deletes the current worktree; migrate may delete a sole default
        # checkout or move the source tree out from under the shell.
        local previous_dir=$PWD
        cd "$HOME" || return $?
        (
            cd "$previous_dir" || exit $?
            command git-wt "$@"
        ) || return $?
        cd "$HOME"
        ;;
    *)
        command git-wt "$@"
        ;;
    esac
}
`

	return os.WriteFile(target, []byte(content), 0o644)
}

func (x *zshCommandOptions) writeCompletionFile(target string) error {
	content := `#compdef ` + x.name + `

# Generated by git-wt generate zsh
# DO NOT EDIT. Regenerate with git-wt generate zsh

_` + x.name + `() {
    local context state state_descr line
    typeset -A opt_args

    local -a subcommands
    subcommands=(
        'create:Create a managed Git worktree'
        'list:List managed Git worktrees'
        'migrate:Register current repository and rehome worktrees'
        'prune:Remove clean merged managed worktrees'
        'remove:Remove a managed Git worktree'
        'repo:Manage registered repositories'
        'generate:Generate shell integration'
        'switch:Switch to a worktree'
    )

    if (( CURRENT == 2 )); then
        _describe 'command' subcommands
        return
    fi

    case $words[2] in
    create)
        shift words
        (( CURRENT-- ))
        _arguments \
            '--no-cd[Create without changing directories]' \
            '--repo[Registered repository name]:repository:->repos' \
            '--current[Use repository for the current worktree]' \
            '(-r --herdr)'{-r,--herdr}'[Also create a Herdr workspace for the new worktree]' \
            '(-R --no-herdr)'{-R,--no-herdr}'[Do not create a Herdr workspace]' \
            '(-u --upstream)'{-u,--upstream}'[Upstream branch]:upstream branch:' \
            '(-h --help)'{-h,--help}'[help for create]' \
            '1:worktree name:'
        ;;
    list)
        shift words
        (( CURRENT-- ))
        _arguments \
            '(--all)--repo[Registered repository name]:repository:->repos' \
            '(--repo)--all[List worktrees from all registered repositories]' \
            '(-h --help)'{-h,--help}'[help for list]'
        ;;
    switch|remove)
        shift words
        (( CURRENT-- ))
        _arguments \
            '--repo[Registered repository name]:repository:->repos' \
            '1:worktree name:->worktrees'
        ;;
    prune)
        shift words
        (( CURRENT-- ))
        _arguments \
            '--repo[Registered repository name]:repository:->repos' \
            '(-p --prompt)'{-p,--prompt}'[Prompt before pruning]' \
            '(-h --help)'{-h,--help}'[help for prune]'
        ;;
    repo)
        local -a repo_commands
        repo_commands=(
            'add:Register a bare repository'
            'list:List registered repositories'
            'remove:Remove a registered repository'
        )
        if (( CURRENT == 3 )); then
            _describe 'repo command' repo_commands
            return
        fi
        case $words[3] in
        remove)
            state=repos
            ;;
        esac
        ;;
    esac

    case $state in
    repos)
        local -a repos
        local data_home=${XDG_DATA_HOME:-$HOME/.local/share}
        local repo_dir
        for repo_dir in "$data_home"/git-wt/repos/*.git(N/); do
            repos+=("${repo_dir:t:r}")
        done
        _describe 'repositories' repos
        ;;
    worktrees)
        local repo_name=""
        local i
        for (( i = 1; i <= $#words; i++ )); do
            case ${words[i]} in
            --repo)
                repo_name=${words[i+1]}
                ;;
            --repo=*)
                repo_name=${words[i]#--repo=}
                ;;
            esac
        done
        if [[ -z "$repo_name" ]]; then
            local common
            common=$(git rev-parse --path-format=absolute --git-common-dir 2>/dev/null) || return 0
            repo_name=${common:t}
            repo_name=${repo_name%.git}
        fi
        local -a worktrees
        local worktree_dir parent name
        local worktree_root=${GIT_WT_WORKTREE_ROOT:-$HOME/worktrees}
        for worktree_dir in "$worktree_root"/**/"$repo_name"(N/); do
            parent=${worktree_dir:h}
            name=${parent#$worktree_root/}
            if [[ -n "$name" && "$name" != "$parent" ]]; then
                worktrees+=("$name")
            fi
        done
        _describe 'worktrees' worktrees
        ;;
    esac
}
`

	return os.WriteFile(target, []byte(content), 0o644)
}
